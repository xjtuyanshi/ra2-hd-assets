/**
 * Live effects: the engine's own effect list (src/games/yr/effectsReader.ts on the host side) drawn in two layers.
 *
 *   1. Native art (the faithful base): every anim the engine plays is drawn with its ORIGINAL SHP frames from the
 *      effect art sidecar (effectArt.ts / effectSprites.ts), at the engine's position, frame, layer and translucency.
 *      Enhanced style can replace those pixels with optional HD flipbooks, retaining the engine frame clock and
 *      placement. An anim disappears when it leaves the engine's list, so its lifetime is native by construction.
 *   2. HD garnish: table-driven light, sparks, flame or smoke per anim type (effectTable.ts, generated by
 *      `pnpm hd:effects`). Faithful garnish stays bounded by the native art; enhanced garnish follows the displayed
 *      footprint and adds lingering smoke and debris. The camera never shakes.
 *
 * Smoke particle systems (damaged and burning units and buildings) are drawn as their ORIGINAL particles: the view
 * runs the system's particles itself (smokeParticles, calibrated against the engine's own particle positions) and draws
 * each with the ParticleType's SHP frames, because the page does not forward particle positions. Beams (lasers,
 * electric bolts) are rebuilt once per logic frame.
 *
 * All timing is in logic frames: garnish lifetimes convert with the measured logic rate, and without the bridge's exact
 * anim frame the fallback frame follows the engine's stage rule from the anim's first appearance.
 */

/** How much HD adds around the engine's own effects (LiveEffectsDriver.style). */
export type EffectStyle = 'faithful' | 'enhanced';

