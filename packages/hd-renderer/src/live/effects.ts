/** A simulated smoke particle: birth frame and spawn point (leptons), launch speed factor and sideways drift. */
export interface SmokeParticle {
  born: number;
  x: number;
  y: number;
  z: number;
  /** Launch speed as a fraction of the rules Velocity (SMOKE_RISE_MIN .. SMOKE_RISE_MAX). */
  rise: number;
  driftX: number;
  driftY: number;
}

/**
 * Smoke particle kinematics measured on the engine's own particles (reader particle positions and identities,
 * SmallGreySSys on XMP29U2: 541 particles followed from birth to removal): a particle appears SMOKE_SPAWN_LIFT leptons
 * above the system and rises at 0.83-1.05 x the rules Velocity (least-squares launch speed 8.42 of Velocity 9, deceleration
 * 0.0499 per frame against Deacc .05; its rise over the first 60 frames spans 6-8 leptons a frame), drifts sideways at
 * up to SMOKE_DRIFT leptons a frame (measured late drift: median 1.8, 90th percentile 3.3) after a SMOKE_DRIFT_ONSET
 * frame onset, advances one SHP frame every StateAIAdvance frames and is removed at EndStateAI (lived 75-80 frames).
 * Without the bridge's lifetime a finite system spawns for SMOKE_SPAWN_WINDOW frames after it is first listed (every
 * refinery and building smoke system measured started at lifetime 48-49), then its particles rise out.
 */
export const SMOKE_SPAWN_LIFT = 10;
export const SMOKE_RISE_MIN = 0.83;
export const SMOKE_RISE_MAX = 1.05;
export const SMOKE_DRIFT = 3.6;
export const SMOKE_DRIFT_ONSET = 30;
export const SMOKE_SPAWN_WINDOW = 48;
/** The system type assumed when the bridge does not name it: the damage smoke of vehicles and structures. */
const DEFAULT_SMOKE_SYSTEM = 'SmallGreySSys';

/** Rules of a smoke system by type id, or the default system's. */
export function smokeSystemRules(type: string | undefined): SmokeSystemRow | undefined {
  return (type ? SMOKE_SYSTEMS[type] : undefined) ?? SMOKE_SYSTEMS[DEFAULT_SMOKE_SYSTEM];
}

/** Lepton position and SHP frame of a smoke particle `age` logic frames after its birth, or null once removed. */
export function smokeParticleAt(
  p: SmokeParticle,
  rules: SmokeSystemRow,
  age: number,
): { x: number; y: number; z: number; frame: number } | null {
  const life = rules.endState * rules.stateAdvance;
  if (age < 0 || age >= life) return null;
  const v0 = rules.velocity * p.rise;
  // Rise while the velocity lasts (it never turns downward).
  const t = rules.deacc > 0 ? Math.min(age, v0 / rules.deacc) : age;
  const rise = v0 * t - 0.5 * rules.deacc * t * t;
  // Sideways drift eases in over the onset, then keeps its speed.
  const drift = age < SMOKE_DRIFT_ONSET ? (age * age) / (2 * SMOKE_DRIFT_ONSET) : age - SMOKE_DRIFT_ONSET / 2;
  return {
    x: p.x + p.driftX * drift,
    y: p.y + p.driftY * drift,
    z: p.z + SMOKE_SPAWN_LIFT + rise,
    frame: Math.min(rules.endState - 1, Math.floor(age / Math.max(1, rules.stateAdvance))),
  };
}

/** Deterministic 0..1 value for a particle (system uid, spawn index, channel). */
function hash01(a: number, b: number, c: number): number {
  let h = Math.imul(a ^ 0x9e3779b9, 0x85ebca6b) ^ Math.imul(b + 0x632be5ab, 0xc2b2ae35) ^ Math.imul(c + 1, 0x27d4eb2f);
  h = Math.imul(h ^ (h >>> 15), 0x2c1b3c6d);
  h = Math.imul(h ^ (h >>> 12), 0x297a2d39);
  return ((h ^ (h >>> 15)) >>> 0) / 4294967296;
}

export class LiveEffectsDriver {
  private readonly anims = new Map<string, TrackedAnim>();
  private clusters: FireballCluster[] = [];
  private readonly systems = new Map<string, TrackedSystem>();
  private bullets: LiveBullet[] = [];
  private beams: LiveBeam[] = [];
  private decorativeBeams: readonly BeamSpec[] = [];
  private decorativeState = '[]';
  private readonly beamTail: LiveBeam[] = [];
  private beamFrame = NaN;
  private beamState = '';
  private readonly bulletAt = new Vector3();
  private generation = 0;
  private lastPush: { frame: number; seconds: number } | null = null;
  /** Renderer clock of the newest push, including another push of the same logic frame. */
  private pushedAt = 0;
  /** Logic frames per second, an EMA of the snapshot frame rate (the engine's GameSpeed and emulation speed vary). */
  logicFps = 15;
  /** Logic frame of the newest snapshot. */
  logicFrame = 0;
  /** Anim types seen without art (diagnostics). */
  readonly unknownTypes = new Set<string>();
  /** HD garnish on top of the native art (off = the original effects only, for comparisons). */
  garnishEnabled = true;
  /** The live view's opt-out for RGBA flipbooks; native art and procedural garnish keep their existing behavior. */
  hdEnabled = true;
  /** Opt-in procedural volumes for large blasts in enhanced style. */
  volumetric: 'off' | 'ray' = 'off';
  /**
   * 'faithful' (default): the garnish stays inside the native art's footprint and lifetime. 'enhanced': the remaster's
   * modern effects around it (EffectsLayer ENHANCED: a real flash of light, glow halo and bloom, rolling lit smoke,
   * sparks and debris, heat shimmer, dust ring, a cooling hot crater). Optional HD flipbooks replace the native pixels
   * at the same engine frame, size and placement; the persistent crater stays the engine's own smudge.
   */
  style: EffectStyle = 'faithful';

  constructor(
    private readonly effects: EffectsLayer,
    /** True when a lepton location is hidden under black shroud (nothing is spawned or drawn there). */
    private readonly hidden: (x: number, y: number, z: number) => boolean,
    /** Whether a projectile type has native art (drawn by the projectile layer instead of a grey dot). */
    private readonly bulletArt: (type: string) => boolean = () => false,
  ) {}

  /** A new snapshot arrived (logic frame `frame`, renderer clock `now` in seconds). */
  push(effects: LiveEffects, frame: number, now: number, wind: Vector3): void {
    const generation = ++this.generation;
    this.pushedAt = now;
    if (this.lastPush && frame > this.lastPush.frame && now > this.lastPush.seconds) {
      const fps = (frame - this.lastPush.frame) / (now - this.lastPush.seconds);
      if (Number.isFinite(fps) && fps > 1 && fps < 120) this.logicFps += (fps - this.logicFps) * 0.1;
    }
    if (!this.lastPush || frame !== this.lastPush.frame) this.lastPush = { frame, seconds: now };
    this.logicFrame = frame;
    const fresh: TrackedAnim[] = [];
    for (const anim of effects.anims) {
      if (anim.buildingAnim) continue;
      const key = `${anim.id}:${anim.uid}`;
      let tracked = this.anims.get(key);
      if (!tracked || tracked.anim.type !== anim.type) {
        // New anim, or the same object chained to its Next type (BURN-L -> M -> S): its own art and garnish.
        const row = effectRow(anim.type);
        tracked = {
          anim,
          row,
          lightKey: `anim:${key}`,
          since: frame,
          lastSeen: generation,
          nextEmit: now,
          at: new Vector3(),
        };
        this.anims.set(key, tracked);
        world(anim, tracked.at);
        fresh.push(tracked);
      }
      tracked.anim = anim;
      tracked.lastSeen = generation;
      world(anim, tracked.at);
    }
    for (const [key, tracked] of this.anims) if (tracked.lastSeen !== generation) this.anims.delete(key);
    this.mergeFireballs(fresh, now);
    for (const tracked of fresh) {
      const { anim } = tracked;
      if (tracked.merge?.absorbed || this.hidden(anim.x, anim.y, anim.z)) continue;
      this.garnish(tracked, now, wind);
    }
    for (const system of effects.particleSystems) {
      if (system.behaviour !== 'smoke' && system.behaviour !== 'fire') continue;
      const key = `${system.id}:${system.uid}`;
      let tracked = this.systems.get(key);
      if (!tracked) {
        tracked = {
          system,
          lightKey: `system:${key}`,
          lastSeen: generation,
          nextEmit: now,
          at: new Vector3(),
          since: frame,
          smoke: [],
          spawned: 0,
          unlimited: smokeUnlimited(system, this.vehicleAt),
        };
        this.systems.set(key, tracked);
      }
      tracked.system = system;
      tracked.lastSeen = generation;
      world(system, tracked.at);
      if (system.behaviour === 'smoke') advanceSmoke(tracked, frame);
    }
    for (const [key, tracked] of this.systems) if (tracked.lastSeen !== generation) this.systems.delete(key);
    this.bullets.length = 0;
    for (const bullet of effects.bullets) if (!this.hidden(bullet.x, bullet.y, bullet.z)) this.bullets.push(bullet);
    // EBolt lifetime is decremented by a draw pass, not solely by logic AI. A replacement publication can remove
    // beams while CurrentFrame is unchanged; display refreshes alone still leave their shape untouched.
    const beamState = JSON.stringify(effects.beams ?? []);
    if (frame !== this.beamFrame || beamState !== this.beamState) {
      this.beamFrame = frame;
      this.beamState = beamState;
      this.beams.length = 0;
      let tailCount = 0;
      let tailCursor = 0;
      if (effects.beams)
        for (const beam of effects.beams) {
          if (this.hidden(beam.target.x, beam.target.y, beam.target.z)) continue;
          if (this.beams.length < BEAM_SEGMENTS) this.beams.push(beam);
          else {
            this.beamTail[tailCursor] = beam;
            tailCursor = (tailCursor + 1) % BEAM_LIGHTS;
            tailCount = Math.min(tailCount + 1, BEAM_LIGHTS);
          }
        }
      // The first segments and last flash lights are the exact subsets the two existing fixed pools can draw.
      for (let i = 0; i < tailCount; i++)
        this.beams.push(this.beamTail[(tailCursor - tailCount + i + BEAM_LIGHTS) % BEAM_LIGHTS]!);
      this.effects.enhancedBeams = this.garnishEnabled && this.style === 'enhanced';
      this.effects.setBeams(now, this.beamSpecs());
    }
  }

  /**
   * Beams of the newest publication, kept until replaced or removed (also while logic is paused).
   * The HD bolt shape uses a stable seed for each pair of logic frames; it does not reproduce native random paths.
   */
  private beamSpecs(): BeamSpec[] {
    const native = this.beams.map((beam) => {
      const bolt = beam.kind === 'bolt';
      const srgb = bolt ? (isViolet(beam.colour) ? ALTERNATE : TESLA) : beam.colour;
      return {
        from: world(beam.source, new Vector3()),
        to: world(beam.target, new Vector3()),
        colour: new Vector3(Math.pow(srgb[0] / 255, 2.2), Math.pow(srgb[1] / 255, 2.2), Math.pow(srgb[2] / 255, 2.2)),
        bolt,
        seed: (Math.floor(this.logicFrame / 2) * 7919 + Math.round(beam.target.x + beam.target.y * 3)) >>> 0,
      };
    });
    return this.decorativeBeams.length ? [...native, ...this.decorativeBeams] : native;
  }

  /** Replace decorative geometry without retriggering native beam flashes on display refreshes. */
  setDecorativeBeams(now: number, beams: readonly BeamSpec[]): void {
    const state = JSON.stringify(beams);
    if (state === this.decorativeState) return;
    this.decorativeState = state;
    this.decorativeBeams = beams;
    this.effects.setBeams(now, this.beamSpecs(), false);
  }

  /**
   * Per presented frame: continuous garnish (fire particle systems, unknown projectiles). Looping fires (FIRE01..03,
   * burning buildings) get no HD flame: their original art is the whole flame, and an HD tongue on top doubled its
   * size. They keep a small flickering light alive in the light field (it matters at night), plus a few drifting embers
   * in enhanced style. Smoke systems are drawn as native particles (smokeCards).
   */
  frame(now: number, wind: Vector3): void {
    const enhancedBeams = this.garnishEnabled && this.style === 'enhanced';
    if (this.effects.enhancedBeams !== enhancedBeams) {
      this.effects.enhancedBeams = enhancedBeams;
      // A style switch also redraws a paused bolt; ordinary presented frames only advance its shader clock.
      this.effects.setBeams(now, this.beamSpecs());
    }
    for (const tracked of this.systems.values()) {
      const { system } = tracked;
      if (system.behaviour !== 'fire' || now < tracked.nextEmit || this.hidden(system.x, system.y, system.z)) continue;
      // With the particles themselves reported, their native art is drawn instead of HD garnish.
      if (system.particles) continue;
      this.effects.flame(now, tracked.at, 0.6, tracked.lightKey, { maxSize: FIRE_SYSTEM_FLAME });
      tracked.nextEmit = now + 1 / 10;
    }
    if (this.garnishEnabled)
      for (const tracked of this.anims.values()) {
        const { row, anim } = tracked;
        if (row.fx !== 'fire' || !row.loop || now < tracked.nextEmit || this.hidden(anim.x, anim.y, anim.z)) continue;
        this.effects.fireLight(tracked.lightKey, now, tracked.at, row.s);
        if (this.style === 'enhanced') this.effects.fireEmbers(now, tracked.at, row.s, wind);
        tracked.nextEmit = now + 1 / 5;
      }
    for (const bullet of this.bullets) {
      if (bullet.type && this.bulletArt(bullet.type)) continue;
      this.effects.bulletDot(now, world(bullet, this.bulletAt));
    }
  }

  /**
   * The simulated smoke particles of every smoke system as native particle cards (the particle type's SHP frame at the
   * system type's translucency, drawn in the air pass like the engine's particle layer). Systems whose particles the
   * host reports with their frames are left to the view's own particle cards.
   */
  smokeCards(art: EffectArt, out: EffectInstance[]): number {
    let drawn = 0;
    for (const tracked of this.systems.values()) {
      const { system } = tracked;
      if (system.behaviour !== 'smoke' || system.particles?.some((p) => p.frame !== undefined)) continue;
      const rules = smokeSystemRules(system.type);
      const found = rules ? art.particle(rules.particle) : null;
      if (!rules || !found) continue;
      const alpha = animAlpha({ translucency: rules.translucency });
      for (const particle of tracked.smoke) {
        const at = smokeParticleAt(particle, rules, this.logicFrame - particle.born);
        if (!at || this.hidden(at.x, at.y, at.z)) continue;
        const frame = found.sprite.frames[Math.min(at.frame, found.sprite.frames.length - 1)];
        if (!frame || frame.rect[2] <= 0) continue;
        out.push({
          anchor: engineAnchor(at.x, at.y, at.z),
          frame,
          palette: 'fx:anim',
          alpha,
          push: cardPush(frame),
          draw: 'card',
          pass: 'air',
          depth: engineDepth(at.x, at.y, at.z),
          glow: false,
        });
        drawn++;
      }
    }
    return drawn;
  }

  /** Art of every tracked anim at this engine frame; enhanced style may substitute an optional HD flipbook. */
  cards(
    art: EffectArt,
    palette: (resolved: ResolvedAnim, owner: number | undefined) => string,
    out: EffectInstance[],
  ): { drawn: number; missing: number } {
    let drawn = 0;
    let missing = 0;
    for (const tracked of this.anims.values()) {
      const { anim } = tracked;
      if (this.hidden(anim.x, anim.y, anim.z)) continue;
      const resolved = art.anim(anim.type);
      if (!resolved) {
        if (art.ready) {
          missing++;
          this.unknownTypes.add(anim.type);
        }
        continue;
      }
      if (this.volumePolicy(anim.type)) continue;
      // Absorbed into a merged fireball (FIREBALL_MERGE): the lead draws the cluster.
      if (tracked.merge?.absorbed && this.style === 'enhanced' && this.hdEnabled) continue;
      const { art: a, sprite } = resolved;
      let index = anim.frame;
      if (index === undefined) {
        const age = this.logicFrame - tracked.since;
        // Hold the last frame if the engine keeps the anim a little longer than the fallback timing says.
        index = animFrameAt(a, age, anim.uid) ?? a.start + Math.max(0, a.frameCount - 1);
      }
      const frame = sprite.frames[index];
      if (!frame || frame.rect[2] <= 0) continue;
      const lead = tracked.merge && !tracked.merge.absorbed ? tracked.merge : null;
      const drawAt = lead ?? anim;
      const anchor = engineAnchor(drawAt.x, drawAt.y, drawAt.z, a.drawOffset ?? [0, 0]);
      const flat = anim.flat ?? a.flat ?? false;
      const layer = anim.layer ?? a.layer;
      const pass: EffectPass = flat ? 'ground' : layer === 'top' ? 'top' : layer === 'air' ? 'air' : 'ground';
      const key = palette(resolved, anim.owner);
      const depth = engineDepth(drawAt.x, drawAt.y, drawAt.z) + (a.zAdjust ?? 0) * 0.001;
      // Translucent=yes art fades by stage (animAlpha): the bridge's stage, or the fallback frame's.
      const end = anim.frameCount || a.frameCount;
      const hd = this.hdEnabled && this.style === 'enhanced' ? art.hdAnim(anim.type) : null;
      if (hd) {
        const hdFrame = hd.frames[index];
        // Empty native stages stay empty, including their shadow. Unknown or failed HD pages retain native art.
        if (hdFrame === null) continue;
        if (hdFrame && art.hdPageState(hdFrame.page) !== null) {
          const size = hdSize(tracked.row) * this.mergeSize(tracked, this.pushedAt);
          const rate = Math.max(1, anim.rate ?? a.rateFrames);
          const blend0 = anim.stage === undefined ? ((this.logicFrame - tracked.since) % rate) / rate : 0;
          const loops = anim.loopsLeft ?? a.loopCount;
          const nextIndex = index + 1 < a.loopEnd ? index + 1 : loops < 0 || loops > 1 ? a.loopStart : null;
          const next = nextIndex === null ? null : (hd.frames[nextIndex] ?? null);
          out.push({
            anchor,
            frame,
            palette: key,
            alpha: animAlphaSmooth(
              { translucent: anim.translucent ?? a.translucent, translucency: anim.translucency ?? a.translucency },
              (anim.stage ?? animStage(a, index)) + blend0,
              end,
            ),
            push: flat
              ? 0
              : cardPush({
                  rect: [0, 0, (hdFrame.rect[2] / hd.scale) * size, (hdFrame.rect[3] / hd.scale) * size],
                  offset: [hdFrame.offset[0] * size, hdFrame.offset[1] * size],
                }),
            draw: flat ? 'flat' : 'card',
            pass,
            depth,
            glow: false,
            ...(lead?.depthBias ? { depthBias: lead.depthBias } : {}),
            hd: {
              frame: hdFrame,
              next: next?.page === hdFrame.page ? next : null,
              scale: hd.scale,
              size,
              blend0,
              t0: this.pushedAt,
              stageSeconds: rate / this.logicFps,
            },
          });
          drawn++;
          continue;
        }
      }
      const alpha = animAlpha(
        { translucent: anim.translucent ?? a.translucent, translucency: anim.translucency ?? a.translucency },
        anim.stage ?? animStage(a, index),
        end,
      );
      const shadow = a.shadow ? sprite.shadows?.[index] : undefined;
      if (shadow && shadow.rect[2] > 0)
        out.push({
          anchor,
          frame: shadow,
          palette: key,
          alpha: 1,
          push: 0,
          draw: 'shadow',
          pass: 'ground',
          depth,
          glow: false,
        });
      out.push({
        anchor,
        frame,
        palette: key,
        alpha,
        push: flat ? 0 : cardPush(frame),
        draw: flat ? 'flat' : 'card',
        pass,
        depth,
        glow: cardGlows(a, index, alpha, resolved.remap),
      });
      drawn++;
    }
    return { drawn, missing };
  }

  /**
   * Assigns FIREBALL_MERGE roles to the explosions that appeared in this snapshot (enhanced style with HD flipbooks
   * only; the faithful style and native-only art keep every blast as the engine draws it).
   */
  private mergeFireballs(fresh: readonly TrackedAnim[], now: number): void {
    if (this.style !== 'enhanced' || !this.garnishEnabled || !this.hdEnabled) return;
    const m = FIREBALL_MERGE;
    this.clusters = this.clusters.filter((c) => now - c.t0 <= m.hold && now >= c.t0);
    const blasts = fresh.filter(
      (t) => t.row.c === 'explosion' && t.row.fx === 'explosion' && !this.hidden(t.anim.x, t.anim.y, t.anim.z),
    );
    if (!blasts.length) return;
    const near2 = (a: Vector3, b: Vector3, r: number) => (a.x - b.x) ** 2 + (a.z - b.z) ** 2 <= r * r;
    // This snapshot's blasts, grouped by single linkage: a building's whole Explosion= list is one group.
    const parent = blasts.map((_, i) => i);
    const find = (i: number): number => (parent[i] === i ? i : (parent[i] = find(parent[i]!)));
    for (let i = 0; i < blasts.length; i++)
      for (let j = i + 1; j < blasts.length; j++)
        if (near2(blasts[i]!.at, blasts[j]!.at, m.radius)) parent[find(i)] = find(j);
    const groups = new Map<number, TrackedAnim[]>();
    for (let i = 0; i < blasts.length; i++) {
      const root = find(i);
      groups.set(root, [...(groups.get(root) ?? []), blasts[i]!]);
    }
    const fire = (t: TrackedAnim) => t.row.s * (1 - (t.row.smoke ?? 0));
    const hd = (t: TrackedAnim) => !!this.hasHdArt?.(t.anim.type);
    const alive = (t: TrackedAnim) => this.anims.get(`${t.anim.id}:${t.anim.uid}`) === t;
    const absorb = (t: TrackedAnim) => {
      t.merge = { absorbed: true, size: 1, born: 1, since: now, x: t.anim.x, y: t.anim.y, z: t.anim.z, depthBias: 0 };
    };
    for (const group of groups.values()) {
      // HD art first (only an HD flipbook can be enlarged), then the most fiery blast leads.
      group.sort((a, b) => Number(hd(b)) - Number(hd(a)) || fire(b) - fire(a));
      const near = this.clusters.find(
        (c) => alive(c.lead) && group.some((t) => c.members.some((p) => near2(p, t.at, m.joinRadius))),
      );
      // Retain original foundation bounds without changing the merge's positions, linkage or lead selection.
      const foundation: FoundationExtent = near?.foundation ?? {
        members: 0,
        x: [Infinity, -Infinity],
        z: [Infinity, -Infinity],
      };
      foundation.members += group.length;
      for (const { at } of group) {
        foundation.x[0] = Math.min(foundation.x[0], at.x);
        foundation.x[1] = Math.max(foundation.x[1], at.x);
        foundation.z[0] = Math.min(foundation.z[0], at.z);
        foundation.z[1] = Math.max(foundation.z[1], at.z);
      }
      if (near && (now - near.leadAt <= m.window || near.leads >= m.maxLeads)) {
        for (const t of group) {
          absorb(t);
          near.members.push(t.at.clone());
        }
        near.count += group.length;
        const role = near.lead.merge!;
        // Later members make the lead grow from the size it shows now.
        role.born = this.mergeSize(near.lead, now);
        role.since = now;
        role.size = Math.min(m.maxSize, 1 + m.perMember * (near.count - 1));
        continue;
      }
      const lead = group[0]!;
      if (!hd(lead)) continue;
      for (const t of group.slice(1)) absorb(t);
      // A lead born with its members is drawn at their centroid, at once at the group's size.
      const size = Math.min(m.maxSize, 1 + m.perMember * (group.length - 1));
      const role: MergeRole = {
        absorbed: false,
        size,
        born: size,
        since: now,
        x: group.reduce((sum, t) => sum + t.anim.x, 0) / group.length,
        y: group.reduce((sum, t) => sum + t.anim.y, 0) / group.length,
        z: group.reduce((sum, t) => sum + t.anim.z, 0) / group.length,
        depthBias: 0,
        foundation,
      };
      lead.merge = role;
      world(role, lead.at);
      // A building's death (its Explosion= list, three or more blasts at once) engulfs the building at its centre, but
      // not units beyond the members' spread; smaller merges keep the plain anchor depth (a tank in front stays in front).
      if (group.length >= m.engulfMembers)
        role.depthBias = m.engulf + Math.max(...group.map((t) => Math.hypot(t.at.x - lead.at.x, t.at.z - lead.at.z)));
      const members = group.map((t) => t.at.clone());
      if (near && near.leads < m.maxLeads) {
        Object.assign(near, { lead, leadAt: now, leads: near.leads + 1, count: group.length });
        near.members.push(...members);
      } else this.clusters.push({ lead, t0: now, leadAt: now, leads: 1, count: group.length, members, foundation });
    }
  }

  /** Display-size factor of a merge lead at renderer clock `now` (1 for every other anim). */
  private mergeSize(tracked: TrackedAnim, now: number): number {
    const role = tracked.merge;
    if (!role || role.absorbed) return 1;
    const t = Math.max(0, Math.min(1, (now - role.since) / FIREBALL_MERGE.grow));
    return role.born + (role.size - role.born) * t * t * (3 - 2 * t);
  }

  /** Same selection gate for cards, volumes and the retained HD garnish. */
  private volumePolicy(type: string): (typeof VOLUMETRIC_ANIMS)[string] | undefined {
    return this.style === 'enhanced' && this.garnishEnabled && this.volumetric === 'ray'
      ? VOLUMETRIC_ANIMS[type.toUpperCase()]
      : undefined;
  }

  /** Volumes follow native stages and stop as soon as their anim leaves the snapshot. */
  volumes(art: EffectArt, out: VolumetricBlast[]): void {
    for (const tracked of this.anims.values()) {
      const { anim } = tracked;
      const policy = this.volumePolicy(anim.type);
      if (!policy || this.hidden(anim.x, anim.y, anim.z)) continue;
      const resolved = art.anim(anim.type);
      if (!resolved) continue;
      const a = resolved.art;
      const index =
        anim.frame ??
        animFrameAt(a, this.logicFrame - tracked.since, anim.uid) ??
        a.start + Math.max(0, a.frameCount - 1);
      const frame = resolved.sprite.frames[index];
      if (!frame || frame.rect[2] <= 0) continue;
      const end = Math.max(1, anim.frameCount || a.frameCount);
      const rateFrames = Math.max(1, anim.rate ?? a.rateFrames);
      const blend0 = anim.stage === undefined ? ((this.logicFrame - tracked.since) % rateFrames) / rateFrames : 0;
      const stage = (anim.stage ?? animStage(a, index)) + blend0;
      const rate = this.logicFps / (end * rateFrames);
      out.push({
        anchor: tracked.at.clone(),
        radius: policy.size * pixelsToWorld(a.visW ?? frame.rect[2]) * 0.5,
        progress0: Math.max(0, Math.min(1, stage / end)),
        t0: this.pushedAt,
        rate,
        lifeSeconds: 1 / rate,
        seed: anim.uid,
        style: VOLUMETRIC_BLAST_PRESETS[policy.preset],
        fade: Math.sqrt(
          animAlphaSmooth(
            {
              translucent: anim.translucent ?? a.translucent,
              translucency: anim.translucency ?? a.translucency,
            },
            stage,
            end,
          ),
        ),
        push: cardPush(frame),
      });
    }
  }

  /** Tracked anims (diagnostics and tests). */
  get tracked(): ReadonlyMap<string, { anim: LiveAnim; row: EffectTableRow; since: number }> {
    return this.anims;
  }

  /** Width of an anim's original art in world units; unknown art does not cap the garnish. */
  private widthOf(type: string): number | undefined {
    return this.artWidth?.(type);
  }

  /** Set by the live view once effect art is available: native art width in world units. */
  artWidth: ((type: string) => number | undefined) | null = null;

  /** Set by the live view: whether optional HD art replaces an anim's pixels (queried only in enhanced style). */
  hasHdArt: ((type: string) => boolean) | null = null;

  /** Set by the live view per snapshot: whether a smoke system at a lepton position is a vehicle's (smokeOnVehicle). */
  vehicleAt: ((x: number, y: number, z: number) => boolean) | null = null;

  private garnish(tracked: TrackedAnim, now: number, wind: Vector3): void {
    const { row, at } = tracked;
    if (!this.garnishEnabled) return;
    // The live view never shakes the camera (rows marked `shake` included): the HD picture must stay aligned with the
    // game's own selection boxes, health bars and cursor, which do not shake.
    if (row.fx === 'none' || row.fx === 'bolt') return;
    const seconds = row.life / Math.max(1, this.logicFps);
    const enhanced = this.style === 'enhanced';
    const options: GarnishOptions = {
      maxSize: this.widthOf(tracked.anim.type),
      maxLife: Math.max(0.05, 1.2 * seconds),
      light: row.light ?? null,
      // The engine leaves its own smudge (bridge H3); HD never paints a scorch on its own.
      scorch: false,
      // No HD smoke in the faithful style: the native art's own late frames are the blast's smoke (fading by stage like
      // the engine's), and HD puffs on top drew dense grey columns where frozen live pairs show the original's faint
      // haze. The enhanced style adds its own rolling smoke around the art on purpose.
      smoke: 0,
      enhanced,
      hdArt:
        !!this.volumePolicy(tracked.anim.type) || (enhanced && this.hdEnabled && !!this.hasHdArt?.(tracked.anim.type)),
      // Enhanced: a brief hot crater and faint char accompany the engine's own lasting smudge.
      hotCrater: enhanced && row.scorch === 1,
    };
    // A merge lead carries its cluster: its garnish is sized for the fireball it grows to.
    const merged = tracked.merge && !tracked.merge.absorbed ? tracked.merge.size : 1;
    const foundation = tracked.merge && !tracked.merge.absorbed ? tracked.merge.foundation : undefined;
    if (foundation && foundation.members >= FIREBALL_MERGE.engulfMembers)
      options.charWidth = Math.max(foundation.x[1] - foundation.x[0], foundation.z[1] - foundation.z[0]) + 1;
    if (options.hdArt && options.maxSize !== undefined) options.maxSize *= hdSize(row) * merged;
    if (row.fx === 'explosion') this.effects.explode(now, at, row.s * merged, wind, options);
    else if (row.fx === 'muzzle') this.effects.muzzleFlash(now, at, row.s, options);
    else if (row.fx === 'spark') this.effects.sparkFlash(now, at, row.s, options);
    else if (row.fx === 'impact') this.effects.impact(now, at, row.s, wind, options);
    else if (row.fx === 'smoke') {
      // One puff per anim instance (trail puffs such as SMOKEY2), never a continuous column. The enhanced style keeps
      // them small and brief (ENHANCED.trail): the dozens of debris-trail puffs of a building death accumulated into a
      // flat grey sheet with depth-cut edges, while without any HD puff the native trail art shows as raw octagons.
      const trail = enhanced ? ENHANCED.trail : { maxSize: Infinity, maxLife: Infinity };
      this.effects.smokePuff(now, at, row.s, wind, {
        maxSize: Math.min(options.maxSize ?? Infinity, trail.maxSize),
        maxLife: Math.min(options.maxLife ?? Infinity, trail.maxLife),
      });
    } else if (row.fx === 'fire' && !row.loop)
      this.effects.flame(now, at, row.s, undefined, { maxSize: options.maxSize, maxLife: options.maxLife });
  }
}

/**
 * Stage (StageClass value, 0 .. End - 1) of an anim showing SHP frame `frame` without the bridge's stage: the frame's
 * offset from the art's Start, counted back from the end for Reverse art (animFrameAt).
 */
export function animStage(art: Pick<EffectAnim, 'start' | 'frameCount' | 'reverse'>, frame: number): number {
  const offset = frame - art.start;
  return art.reverse ? Math.max(1, art.frameCount) - 1 - offset : offset;
}

/** Share of a one-shot anim's frames (from its start) that are its bright early part. */
export const GLOW_FRAMES = 0.4;

/**
 * Whether a native card's fire-coloured pixels may glow (FX_GLOW, just over the bloom threshold): only one-shot
 * anim-palette art while it is drawn opaque (muzzle flashes, impact sparks, and a Translucent=yes explosion's solid
 * first fifth) and within its first GLOW_FRAMES. Once translucent an explosion draws like the engine's mix and nothing
 * more; its late frames are a faint haze, never a lit cloud with a bright dot. Looping fires (FIRE01..03) are not
 * boosted either, so bloom never widens them past their art.
 */
export function cardGlows(
  art: Pick<EffectAnim, 'start' | 'frameCount' | 'loopCount'>,
  frame: number,
  alpha: number,
  remap: boolean,
): boolean {
  if (remap || alpha < 1 || art.loopCount < 0) return false;
  return frame - art.start < Math.max(1, art.frameCount) * GLOW_FRAMES;
}

/**
 * Where a damaged vehicle's smoke system sits relative to the vehicle: on it, or at a fixed offset above its rear for
 * some types (reader dumps with attachedTo: MTNK, HTK and DRON at (0, 0, 0), HTNK at (+100, +100, +275) leptons).
 * SMOKE_ON_VEHICLE_XY / _Z bound that offset.
 */
export const SMOKE_ON_VEHICLE_XY = 160;
export const SMOKE_ON_VEHICLE_Z = 320;

/** Whether a smoke system at (x, y, z) belongs to one of `vehicles` (see SMOKE_ON_VEHICLE_XY). */
export function smokeOnVehicle(
  vehicles: readonly { x: number; y: number; z: number }[],
  x: number,
  y: number,
  z: number,
): boolean {
  return vehicles.some(
    (v) =>
      Math.abs(x - v.x) <= SMOKE_ON_VEHICLE_XY &&
      Math.abs(y - v.y) <= SMOKE_ON_VEHICLE_XY &&
      z - v.z >= 0 &&
      z - v.z <= SMOKE_ON_VEHICLE_Z,
  );
}

/**
 * Whether a smoke system spawns for as long as it is listed. A damaged vehicle's smoke system sits on the vehicle
 * (smokeOnVehicle) and is created with an unlimited (negative) lifetime (reader dumps: lifetime -10..-1187 over up to
 * 1,165 frames, attachedTo the vehicle; it keeps smoking after the vehicle is gone); other smoke systems (refinery
 * chimneys, building damage) start with a positive lifetime (48..49) and stop spawning when it runs out. With the
 * bridge's lifetime and attachment that is exact; without them a system first seen on a vehicle counts as the
 * vehicle's.
 */
export function smokeUnlimited(
  system: LiveParticleSystem,
  vehicleAt: ((x: number, y: number, z: number) => boolean) | null,
): boolean {
  if (system.attachedTo) return system.attachedTo.kind === 'vehicle';
  if (system.lifetime !== undefined) return system.lifetime < 0;
  return !!vehicleAt?.(system.x, system.y, system.z);
}

/** Logic frames from a smoke system's first listing to its first particle (measured: 5 to 7). */
const SMOKE_FIRST_SPAWN = 5;

/**
 * Run a smoke system's particles up to logic frame `frame`: spawn every SpawnFrames frames while the system spawns
 * (always when unlimited, else while the bridge's lifetime is positive, else within SMOKE_SPAWN_WINDOW of its first
 * listing) and fewer than ParticleCap live,
 * catching up frames the snapshots skipped; drop particles past EndStateAI.
 */
export function advanceSmoke(
  tracked: { system: LiveParticleSystem; since: number; smoke: SmokeParticle[]; spawned: number; unlimited: boolean },
  frame: number,
): void {
  const rules = smokeSystemRules(tracked.system.type);
  if (!rules) return;
  const life = rules.endState * rules.stateAdvance;
  const { system } = tracked;
  for (;;) {
    const at = tracked.since + SMOKE_FIRST_SPAWN + tracked.spawned * Math.max(1, rules.spawnFrames);
    if (at > frame) break;
    const spawning =
      tracked.unlimited ||
      (system.lifetime !== undefined ? system.lifetime > 0 : at - tracked.since < SMOKE_SPAWN_WINDOW);
    if (!spawning) break;
    const index = tracked.spawned++;
    let alive = 0;
    for (const particle of tracked.smoke) if (at - particle.born < life) alive++;
    if (alive >= rules.cap) continue;
    const r = rules.radius * Math.sqrt(hash01(system.uid, index, 0));
    const a = hash01(system.uid, index, 1) * Math.PI * 2;
    const speed = SMOKE_DRIFT * hash01(system.uid, index, 2);
    const d = hash01(system.uid, index, 3) * Math.PI * 2;
    tracked.smoke.push({
      born: at,
      x: system.x + r * Math.cos(a),
      y: system.y + r * Math.sin(a),
      z: system.z,
      rise: SMOKE_RISE_MIN + (SMOKE_RISE_MAX - SMOKE_RISE_MIN) * hash01(system.uid, index, 4),
      driftX: speed * Math.cos(d),
      driftY: speed * Math.sin(d),
    });
  }
  let count = 0;
  for (const particle of tracked.smoke) if (frame - particle.born < life) tracked.smoke[count++] = particle;
  tracked.smoke.length = count;
}

/** Violet (alternate) bolt colour as the host reports it. */
function isViolet([r, g, b]: [number, number, number]): boolean {
  return r > g * 1.4 && b > g * 1.4;
}

function world(p: { x: number; y: number; z: number }, out: Vector3): Vector3 {
  return out.set(p.x / 256, (p.z / 104) * LEVEL_HEIGHT, p.y / 256);
}

/** World units of an engine pixel width along a card. */
export function pixelsToWorld(px: number): number {
  return px / PX_PER_UNIT;
}
